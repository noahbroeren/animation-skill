#!/usr/bin/env node
/**
 * Writes the cast bible (markdown) and a JSON dump from src/lib/characters/ours.ts, so the documentation always
 * matches the engine data.
 *   node tools/castbible.mjs [--out ../references/cast]
 */
import { build } from "esbuild";
import { mkdirSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2), at = args.indexOf("--out");
const out = resolve(at >= 0 ? args[at + 1] : join(here, "..", "..", "references", "cast"));
const tmp = join(here, ".castbible.tmp.mjs");
await build({ entryPoints: [join(here, "..", "src", "lib", "characters", "ours.ts")], bundle: true, format: "esm", platform: "node", outfile: tmp, logLevel: "error",
  external: ["remotion", "react", "@remotion/*"] });
const m = await import(pathToFileURL(tmp).href + "?t=" + Date.now());
rmSync(tmp, { force: true });
const { OUR_CAST, CORE_IDS } = m;

const look = (s) => {
  const parts = [];
  if (s.hat) parts.push(`hat ${s.hat.style} ${s.hat.color}`);
  if (s.hair) parts.push(`hair ${s.hair.style} ${s.hair.color}`);
  parts.push(`top ${s.top.style ?? "tee"} ${s.top.color}${s.top.accent ? " / " + s.top.accent : ""}${s.top.pattern ? ", " + s.top.pattern + " print" : ""}`);
  if (s.neck) parts.push(`${s.neck.style} ${s.neck.color}`);
  for (const k of ["glasses", "shades", "stache", "beard"]) if (s[k]) parts.push(k);
  if (s.marks?.length) parts.push(s.marks.join(" + "));
  if (s.build && s.build !== "regular") parts.push(s.build);
  if (s.heightHeads) parts.push(`${s.heightHeads} heads (child or teen body)`);
  return parts.join("; ");
};
const groups = ["core", "everyday", "family", "work", "care", "sport", "history", "fantasy"];
const titles = { core: "Core ensemble (recurring)", everyday: "Everyday", family: "Family", work: "Work", care: "Care", sport: "Sport", history: "History", fantasy: "Fantasy and costumes" };
let md = `# Our cast (brand ours-v1)

Generated by \`node tools/castbible.mjs\` from \`src/lib/characters/ours.ts\`; edit the data there, then re-run.
Sheets: \`node tools/render.mjs --project castsheet --format long --stills 10,40,70,100,130,160,190,220,250\`
(line-ups, true heights, core turnarounds, silhouettes, extras) and \`references/sheets/our-cast-v1-lineup.jpg\`.

Use on a board (with \`brand: BRANDS.ours\`):

\`\`\`ts
import { castEntry, extra, signaturePose } from "../../lib/characters/ours";
cast: { milo: castEntry("milo"), boss: castEntry("bigsby"), crowd1: { spec: extra(1), height: 1.7 } }
// a scene variant without editing the character: castEntry("milo", { marks: ["soot"] }), pose skin: ["sunburn"]
\`\`\`

Rules: every character wears the house style (\`BRANDS.ours\`); identity comes from hair or hat, one torso colour
(+ print), one detail, one prop, at most one face accessory, marks, build and height. Core characters keep their look
in every video; the role library is cast per story; extras fill the background with muted colours.

${Object.keys(OUR_CAST).length} characters (${CORE_IDS.length} core) plus \`extra(seed)\` for endless background people.
`;
for (const g of groups) {
  const ids = Object.keys(OUR_CAST).filter((k) => OUR_CAST[k].group === g);
  if (!ids.length) continue;
  md += `\n## ${titles[g]} (${ids.length})\n\n| id | name | role | personality | rest face | signature | height | voice | look |\n|---|---|---|---|---|---|---|---|---|\n`;
  for (const id of ids) {
    const c = OUR_CAST[id];
    md += `| \`${id}\` | ${c.name} | ${c.role} | ${c.traits} | ${c.rest} | ${c.pose}${c.prop ? " + " + c.prop.item : ""} | ${c.height.toFixed(2)} m | ${c.voice} | ${look(c.spec)} |\n`;
  }
}
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "ours-v1.md"), md);
writeFileSync(join(out, "ours-v1.json"), JSON.stringify(OUR_CAST, null, 1));
console.log(`cast bible: ${Object.keys(OUR_CAST).length} characters -> ${join(out, "ours-v1.md")}`);
